"""Generate both language contracts from the pure wire schema; --check is read-only."""
import argparse
import json
from pathlib import Path
import struct
import re

ROOT = Path(__file__).resolve().parents[1]


def native_layout(name, fields, expected_size):
    """No packed structs or host endian assumptions in the wire codec."""
    types={'B':'std::uint8_t','H':'std::uint16_t','I':'std::uint32_t','Q':'std::uint64_t','i':'std::int32_t','f':'float'}
    out=[f'struct {name} {{'];parsed=[];offset=0
    for field,layout in fields:
        match=re.fullmatch(r'(\d*)([BHIQif])',layout)
        if not match:raise ValueError(f'Unsupported native field {field}: {layout}')
        count=int(match[1] or 1);code=match[2];scalar=types[code];field=field.replace('.','_')
        kind=scalar if count==1 else f'std::array<{scalar}, {count}>'
        out.append(f'    {kind} {field}{{}};');parsed.append((field,scalar,count,offset))
        offset+=struct.calcsize('<'+layout)
    if offset!=expected_size:raise ValueError(f'Layout size mismatch: {name}')
    out+=['};',f'inline {name} decode_{name}(const std::uint8_t* bytes, std::size_t size) {{',
          f'    if (!bytes || size != {offset}) throw std::invalid_argument("{name} wire size");',f'    {name} value;']
    for field,scalar,count,at in parsed:
        if count==1:out.append(f'    value.{field}=wire_read<{scalar}>(bytes+{at});')
        else:out.append(f'    for(std::size_t i=0;i<{count};++i) value.{field}[i]=wire_read<{scalar}>(bytes+{at}+i*sizeof({scalar}));')
    out+=['    return value;', '}', f'inline std::array<std::uint8_t, {offset}> encode_{name}(const {name}& value) {{',
          f'    std::array<std::uint8_t, {offset}> bytes{{}};']
    for field,scalar,count,at in parsed:
        if count==1:out.append(f'    wire_write(bytes.data()+{at},value.{field});')
        else:out.append(f'    for(std::size_t i=0;i<{count};++i) wire_write(bytes.data()+{at}+i*sizeof({scalar}),value.{field}[i]);')
    out+=['    return bytes;','}']
    return out


def outputs():
    schema = json.loads((ROOT / 'src/format/schema.json').read_text())
    constants = schema['constants']
    py = ['# Generated by tools/generate_gpa_format.py. Do not edit.', 'import struct', '']
    cpp = ['// Generated by tools/generate_gpa_format.py. Do not edit.', '#pragma once',
           '#include <cstddef>', '#include <cstdint>', '#include <cstring>', '#include <array>',
           '#include <stdexcept>', '#include <type_traits>', 'namespace flora::format {']
    for name, value in constants.items():
        py.append(f'{name} = {value}')
        cpp.append(f'inline constexpr std::size_t {name} = {value};')
    for name, layout in schema['layouts'].items():
        py.append(f'{name.upper()} = struct.Struct("<{layout}")')
        cpp.append(f'inline constexpr std::size_t {name.upper()}_WIRE_SIZE = {struct.calcsize("<"+layout)};')
    offset = 0
    py.append('STATE_FIELDS = (')
    for name, layout in schema['state_fields']:
        py.append(f'    ({name!r}, {offset}, struct.Struct("<{layout}")),')
        cpp.append(f'inline constexpr std::size_t STATE_{name.upper().replace(".", "_")}_OFFSET = {offset};')
        offset += struct.calcsize('<'+layout)
    py.append(')')
    if offset != constants['STATE_SIZE']:
        raise ValueError('State schema size mismatch')
    cpp+=['template<class T> inline T wire_read(const std::uint8_t* p) {',
          '    using Bits=std::conditional_t<sizeof(T)==8,std::uint64_t,std::conditional_t<sizeof(T)==4,std::uint32_t,std::conditional_t<sizeof(T)==2,std::uint16_t,std::uint8_t>>>;',
          '    Bits bits=0; for(std::size_t i=0;i<sizeof(T);++i) bits=static_cast<Bits>(bits | (static_cast<std::uint64_t>(p[i])<<(i*8)));',
          '    T value; std::memcpy(&value,&bits,sizeof(T)); return value;', '}',
          'template<class T> inline void wire_write(std::uint8_t* p,T value) {',
          '    using Bits=std::conditional_t<sizeof(T)==8,std::uint64_t,std::conditional_t<sizeof(T)==4,std::uint32_t,std::conditional_t<sizeof(T)==2,std::uint16_t,std::uint8_t>>>;',
          '    Bits bits=0; std::memcpy(&bits,&value,sizeof(T));',
          '    for(std::size_t i=0;i<sizeof(T);++i) p[i]=static_cast<std::uint8_t>(static_cast<std::uint64_t>(bits)>>(i*8));', '}']
    for name,layout in schema['layouts'].items():
        fields=schema['layout_fields'][name]
        if ''.join(x[1] for x in fields)!=layout:raise ValueError(f'Named layout disagrees with schema: {name}')
        cpp+=native_layout(name,fields,struct.calcsize('<'+layout))
    cpp+=native_layout('state_block',schema['state_fields'],constants['STATE_SIZE'])
    cpp.append('} // namespace flora::format')
    return {'src/format/Wire.h': '\n'.join(cpp)+'\n'}


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    for name, content in outputs().items():
        path = ROOT / name
        if args.check:
            if not path.exists() or path.read_text(encoding='utf-8') != content:
                raise SystemExit(f'Stale generated contract: {name}')
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(content, encoding='utf-8', newline='\n')


if __name__ == '__main__':
    main()
