#include "DxbcExecution.h"
#include <algorithm>
#include <tuple>

namespace flora::dxbc_exec {
struct Group::State {
    std::vector<std::unique_ptr<Lane>> lanes;
    std::vector<Lane *> participants;
    using Barrier =
        std::tuple<uint32_t, uint32_t, std::vector<uint32_t>, std::vector<std::pair<uint32_t, uint64_t>>>;
    std::vector<std::optional<Barrier>> barriers;
    std::shared_ptr<Memory> shared;
    CancelCheck cancelled;
    uint64_t sequence = 0, epoch = 0, maxSteps;
    uint64_t samplingBatches = 0;
    uint32_t cursor = 0;
    bool failed = false;
};
Group::Group(const Program &program, Inputs inputs, std::array<uint32_t, 3> groupId, uint64_t maxSteps,
             CancelCheck cancelled)
    : state_(std::make_unique<State>()) {
    const auto size = program.threadGroupSize();
    const auto count = uint64_t(size[0]) * size[1] * size[2];
    if (program.stage() != 5 || !count || count > 1024 || !maxSteps || inputs.sharedMemory)
        throw std::runtime_error("Invalid DXBC thread group configuration");
    for (size_t axis = 0; axis < 3; ++axis)
        if (groupId[axis] >= 65535)
            throw std::runtime_error("DXBC group ID exceeds dispatch limits");
    for (const auto &[reg, value] : inputs.registers)
        if (reg.kind == 32 || reg.kind == 33 || reg.kind == 34 || reg.kind == 36)
            throw std::runtime_error("Thread group system values must be generated by the scheduler");
    uint64_t inputValues = inputs.registers.size();
    for (const auto &[slot, values] : inputs.constantBuffers)
        inputValues += values.size();
    if (inputValues * count > 4 * 1024 * 1024)
        throw std::runtime_error("DXBC group input replication budget exceeded");
    auto &s = *state_;
    s.maxSteps = maxSteps;
    s.cancelled = std::move(cancelled);
    std::map<uint64_t, Buffer> buffers;
    std::map<Register, BufferView> views;
    for (const auto &[slot, declaration] : program.sharedDeclarations()) {
        buffers[slot] = {std::vector<uint8_t>(declaration.bytes), std::vector<uint8_t>(declaration.bytes)};
        views[{31, {slot}}] = {slot, 0, declaration.bytes, declaration.stride};
    }
    s.shared = std::make_shared<Memory>(std::move(buffers), std::move(views), 32768, 32768);
    inputs.sharedMemory = s.shared;
    s.barriers.resize(size_t(count));
    for (uint32_t i = 0; i < count; ++i) {
        checkCancellation(s.cancelled);
        const std::array<uint32_t, 3> local{i % size[0], (i / size[0]) % size[1], i / (size[0] * size[1])};
        inputs.registers[{32, {}}] = {{groupId[0] * size[0] + local[0], groupId[1] * size[1] + local[1],
                                       groupId[2] * size[2] + local[2], 0},
                                      7};
        inputs.registers[{33, {}}] = {{groupId[0], groupId[1], groupId[2], 0}, 7};
        inputs.registers[{34, {}}] = {{local[0], local[1], local[2], 0}, 7};
        inputs.registers[{36, {}}] = {{i, 0, 0, 0}, 1};
        s.lanes.push_back(std::make_unique<Lane>(program, inputs, maxSteps));
        s.participants.push_back(s.lanes.back().get());
    }
}
Group::~Group() = default;
bool Group::finished() const {
    return !state_->failed && std::all_of(state_->lanes.begin(), state_->lanes.end(),
                                          [](const auto &lane) { return lane->finished(); });
}
const Lane &Group::lane(uint32_t index) const { return *state_->lanes.at(index); }
const Memory &Group::sharedMemory() const { return *state_->shared; }
uint64_t Group::samplingBatches() const { return state_->samplingBatches; }
GroupStep Group::step() {
    auto &s = *state_;
    if (s.failed)
        throw std::runtime_error("Recreate the DXBC thread group after a failed step");
    try {
        checkCancellation(s.cancelled);
        if (s.sequence >= s.maxSteps)
            throw std::runtime_error("DXBC thread group step budget exceeded");
        const auto count = uint32_t(s.lanes.size());
        uint32_t selected = count;
        for (uint32_t i = 0; i < count; ++i) {
            const auto index = (s.cursor + i) % count;
            if (!s.lanes[index]->finished() && !s.lanes[index]->blocked()) {
                selected = index;
                break;
            }
        }
        if (selected == count)
            throw std::runtime_error("DXBC thread group has no executable lane");
        if (s.lanes[selected]->prepareSamplingBatch(s.participants))
            ++s.samplingBatches;
        GroupStep result{s.sequence, s.epoch, selected, s.lanes[selected]->step(), false};
        if (result.step.syncFlags & 0x800)
            s.barriers[selected] = std::make_tuple(result.step.instruction, result.step.syncFlags,
                                                   result.step.callstack, result.step.syncLoopIterations);
        const auto blocked =
            std::count_if(s.lanes.begin(), s.lanes.end(), [](const auto &lane) { return lane->blocked(); });
        if (blocked &&
            std::any_of(s.lanes.begin(), s.lanes.end(), [](const auto &lane) { return lane->finished(); }))
            throw std::runtime_error("Divergent DXBC barrier with a terminated thread");
        if (blocked == count) {
            for (const auto &barrier : s.barriers)
                if (!barrier || barrier != s.barriers.front())
                    throw std::runtime_error("DXBC threads reached different dynamic barriers");
            for (auto &lane : s.lanes)
                lane->releaseBarrier();
            std::fill(s.barriers.begin(), s.barriers.end(), std::nullopt);
            result.releasedBarrier = true;
            ++s.epoch;
        }
        ++s.sequence;
        s.cursor = (selected + 1) % count;
        return result;
    } catch (...) {
        s.failed = true;
        throw;
    }
}
} // namespace flora::dxbc_exec
